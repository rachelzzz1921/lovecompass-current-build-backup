#!/usr/bin/env node
/**
 * Prepare .env.local for local preview.
 * Vercel env pull often returns empty strings for browser keys — we merge .env.preview defaults.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envLocal = join(root, ".env.local");
const envDevLocal = join(root, ".env.development.local");
const envPreview = join(root, ".env.preview");
const vercelProject = "lovecompass-web";

const DEV_OVERRIDES = `# Auto-generated by npm run env:sync — local dev only (gitignored)
# For full local stack, run: node ../scripts/bootstrap-local-env.mjs
VITE_LOVECOMPASS_API_BASE_URL=http://localhost:8000
VITE_LOVECOMPASS_API_USE_LOCAL=true
VITE_AUTO_MIRROR_FOR_CN=false
`;

const REQUIRED = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "VITE_LOVECOMPASS_API_BASE_URL",
];

function parseEnv(text) {
  const map = new Map();
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map.set(key, value);
  }
  return map;
}

function serializeEnv(map) {
  const lines = ["# Generated by npm run env:sync — do not commit secrets beyond publishable keys"];
  for (const [key, value] of map.entries()) {
    if (key.startsWith("VERCEL_") || key.startsWith("TURBO_") || key === "NX_DAEMON") continue;
    lines.push(`${key}=${value.includes(" ") ? `"${value}"` : value}`);
  }
  return `${lines.join("\n")}\n`;
}

function loadFile(path) {
  if (!existsSync(path)) return new Map();
  return parseEnv(readFileSync(path, "utf8"));
}

function isFilled(value) {
  return typeof value === "string" && value.trim().length > 0;
}

function mergeEnv(...layers) {
  const out = new Map();
  for (const layer of layers) {
    for (const [key, value] of layer.entries()) {
      if (isFilled(value)) out.set(key, value.trim());
    }
  }
  return out;
}

function run(cmd, args) {
  const result = spawnSync(cmd, args, {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, NPM_CONFIG_CACHE: process.env.NPM_CONFIG_CACHE || "/tmp/npm-cache" },
  });
  return result.status === 0;
}

if (!existsSync(envPreview)) {
  console.error("[env:sync] Missing .env.preview — cannot seed local preview defaults.");
  process.exit(1);
}

console.log("[env:sync] Linking Vercel project:", vercelProject);
run("npx", ["--yes", "vercel@latest", "link", "--project", vercelProject, "--yes"]);

console.log("[env:sync] Pulling Vercel production env (may contain empty placeholders) …");
run("npx", ["--yes", "vercel@latest", "env", "pull", ".env.local", "--yes", "--environment=production"]);

const merged = mergeEnv(loadFile(envPreview), loadFile(envLocal));
writeFileSync(envLocal, serializeEnv(merged), "utf8");
writeFileSync(envDevLocal, DEV_OVERRIDES, "utf8");

const missing = REQUIRED.filter((name) => !isFilled(merged.get(name)));
if (missing.length) {
  console.error("[env:sync] Still missing after merge:", missing.join(", "));
  process.exit(1);
}

console.log("[env:sync] OK — .env.local ready (merged .env.preview + Vercel pull)");
console.log("[env:sync] API →", merged.get("VITE_LOVECOMPASS_API_BASE_URL"));
