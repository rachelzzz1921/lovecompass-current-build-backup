#!/usr/bin/env node
/**
 * Prepare frontend + backend env for local full-stack dev.
 * - Frontend → http://localhost:8000 (via .env.development.local, survives env:sync)
 * - Backend  → backend/.env from .env.example + Supabase keys from frontend/.env.preview
 *
 * You must set DATABASE_URL + SUPABASE_JWT_SECRET in backend/.env once (Supabase Dashboard).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const frontendRoot = join(root, "frontend");
const backendRoot = join(root, "backend");

const paths = {
  fePreview: join(frontendRoot, ".env.preview"),
  feDevLocal: join(frontendRoot, ".env.development.local"),
  beExample: join(backendRoot, ".env.example"),
  beEnv: join(backendRoot, ".env"),
};

function parseEnv(text) {
  const map = new Map();
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map.set(key, value);
  }
  return map;
}

function serializeEnvLines(entries) {
  return entries.map(([key, value]) => `${key}=${value.includes(" ") ? `"${value}"` : value}`).join("\n");
}

function readMap(path) {
  if (!existsSync(path)) return new Map();
  return parseEnv(readFileSync(path, "utf8"));
}

function upsertEnvFile(path, header, updates) {
  const existing = readMap(path);
  for (const [key, value] of Object.entries(updates)) {
    if (value !== undefined && value !== "") existing.set(key, value);
  }
  const body = serializeEnvLines([...existing.entries()]);
  writeFileSync(path, `${header}\n${body}\n`, "utf8");
}

// ── Frontend: force local API in dev ──
const feDevHeader = `# Auto-generated by scripts/bootstrap-local-env.mjs — local full-stack dev
# Loaded after .env.local; overrides Vercel remote API for npm run dev`;
upsertEnvFile(paths.feDevLocal, feDevHeader, {
  VITE_LOVECOMPASS_API_BASE_URL: "http://localhost:8000",
  VITE_LOVECOMPASS_API_USE_LOCAL: "true",
  VITE_AUTO_MIRROR_FOR_CN: "false",
});

// ── Backend: seed .env if missing or patch empty keys ──
const preview = readMap(paths.fePreview);
const example = readMap(paths.beExample);
const existingBe = readMap(paths.beEnv);

const supabaseUrl =
  preview.get("NEXT_PUBLIC_SUPABASE_URL") ||
  preview.get("VITE_SUPABASE_URL") ||
  example.get("SUPABASE_URL") ||
  "";
const anonKey =
  preview.get("NEXT_PUBLIC_SUPABASE_ANON_KEY") ||
  preview.get("VITE_SUPABASE_ANON_KEY") ||
  example.get("NEXT_PUBLIC_SUPABASE_ANON_KEY") ||
  "";
const publishable =
  preview.get("VITE_SUPABASE_PUBLISHABLE_KEY") ||
  example.get("SUPABASE_PUBLISHABLE_KEY") ||
  anonKey;

const databaseUrlRaw = process.env.DATABASE_URL?.trim() || existingBe.get("DATABASE_URL") || "";
let databaseUrl = databaseUrlRaw;
if (
  databaseUrl &&
  databaseUrl.includes(":6543/") &&
  !databaseUrl.includes("pgbouncer=true")
) {
  databaseUrl = databaseUrl.includes("?")
    ? `${databaseUrl}&pgbouncer=true`
    : `${databaseUrl}?pgbouncer=true`;
}
const jwtSecret =
  process.env.SUPABASE_JWT_SECRET?.trim() || existingBe.get("SUPABASE_JWT_SECRET") || "";

const beHeader = `# Local backend env — gitignored. Generated/updated by scripts/bootstrap-local-env.mjs
# Fill DATABASE_URL + SUPABASE_JWT_SECRET from Supabase Dashboard if still empty.`;

const beUpdates = {
  DATABASE_URL: databaseUrl || "postgresql://postgres.YOUR_PROJECT_REF:YOUR_PASSWORD@aws-0-REGION.pooler.supabase.com:6543/postgres?pgbouncer=true",
  DIRECT_URL: existingBe.get("DIRECT_URL") || example.get("DIRECT_URL") || "",
  SUPABASE_URL: existingBe.get("SUPABASE_URL") || supabaseUrl,
  SUPABASE_PROJECT_ID:
    existingBe.get("SUPABASE_PROJECT_ID") ||
    preview.get("VITE_SUPABASE_PROJECT_ID") ||
    "wjfpglsygkbpubanylug",
  SUPABASE_PUBLISHABLE_KEY: existingBe.get("SUPABASE_PUBLISHABLE_KEY") || publishable,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: existingBe.get("NEXT_PUBLIC_SUPABASE_ANON_KEY") || anonKey,
  SUPABASE_JWT_SECRET: jwtSecret || "YOUR_SUPABASE_JWT_SECRET",
  LOVECOMPASS_ALLOW_DEMO_USER_FALLBACK: existingBe.get("LOVECOMPASS_ALLOW_DEMO_USER_FALLBACK") || "true",
  CORS_ORIGINS:
    existingBe.get("CORS_ORIGINS") ||
    "http://localhost:5173,http://127.0.0.1:5173,http://localhost:4173,http://127.0.0.1:4173",
  AI_PROVIDER: existingBe.get("AI_PROVIDER") || "mock",
  LOVECOMPASS_UNIVERSAL_CODE: existingBe.get("LOVECOMPASS_UNIVERSAL_CODE") || "MIRROR-ALL-ACCESS",
};

if (existsSync(paths.beEnv)) {
  upsertEnvFile(paths.beEnv, beHeader, beUpdates);
} else {
  writeFileSync(
    paths.beEnv,
    `${beHeader}\n${serializeEnvLines(Object.entries(beUpdates))}\n`,
    "utf8",
  );
}

console.log("");
console.log("──────────────── bootstrap-local-env ────────────────");
console.log("  frontend/.env.development.local → API http://localhost:8000");
console.log("  backend/.env                    →", paths.beEnv);

const missing = [];
if (!databaseUrl || databaseUrl.includes("YOUR_PASSWORD")) missing.push("DATABASE_URL");
if (!jwtSecret || jwtSecret === "YOUR_SUPABASE_JWT_SECRET") missing.push("SUPABASE_JWT_SECRET");

if (missing.length) {
  console.log("");
  console.log("  ⚠ Still required in backend/.env:");
  for (const key of missing) console.log(`    - ${key}`);
  console.log("");
  console.log("  Supabase Dashboard → Project Settings:");
  console.log("    • Database → Connection string (Transaction pooler, port 6543)");
  console.log("    • API → JWT Secret (legacy) or use JWKS via SUPABASE_URL");
  console.log("");
  console.log("  Or run once:");
  console.log("    DATABASE_URL='postgresql://...' SUPABASE_JWT_SECRET='...' node scripts/bootstrap-local-env.mjs");
} else {
  console.log("  ✓ DATABASE_URL and SUPABASE_JWT_SECRET look configured");
}
console.log("────────────────────────────────────────────────────");
console.log("");
